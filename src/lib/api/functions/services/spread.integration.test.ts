const DAY = (d: string) => new Date(`${d}T12:00:00Z`);
/** A real calendar month — a fixed 31-day window would swallow the next month's slice. */
const MONTH = (d: string) => {
  const [year, month] = d.split("-").map(Number);
  return {
    start: new Date(Date.UTC(year, month - 1, 1, 0, 0, 0)),
    end: new Date(Date.UTC(year, month, 1, 0, 0, 0) - 1),
  };
};

const USER = "spread-user";
let businessId: string;
let sourceId: string;
let kilnItemId: string;

before(async () => {
  const admin = new pg.Client({ connectionString: ADMIN_URL });
  await admin.connect();
  try {
    await admin.query(`CREATE DATABASE ${TEST_DB_NAME}`);
  } catch (err) {
    if ((err as { code?: string }).code !== "42P04") throw err; // already exists
  }
  await admin.end();

  await migrate(db, { migrationsFolder: MIGRATIONS });
  await db.execute(
    `TRUNCATE transaction_lines, transactions, cost_components, revenue_item_sources, revenue_items, expense_items, categories, sources, businesses CASCADE`,
  );

  const business = await ensureBusiness(USER);
  businessId = business.id;
  sourceId = (await getManualSource(businessId))!.id;
  const kiln = await catalog.findOrCreateExpenseItem(businessId, {
    name: "Kiln",
    type: "operational",
    costNature: "fixed",
  });
  kilnItemId = kiln.id;
});

after(async () => {
  await pool.end();
});

/** Every slice generated by a purchase, oldest first. */
async function slicesOf(parentId: string) {
  const headers = await db
    .select()
    .from(transactionsTable)
    .where(eq(transactionsTable.parentTransactionId, parentId));
  const lines = headers.length
    ? await db
        .select()
        .from(transactionLinesTable)
        .where(inArray(transactionLinesTable.transactionId, headers.map((h) => h.id)))
    : [];
  return headers
    .map((header) => ({
      header,
      amountCents: lines
        .filter((l) => l.transactionId === header.id)
        .reduce((sum, l) => sum + l.unitPriceCents, 0),
    }))
    .sort((a, b) => a.header.occurredAt.getTime() - b.header.occurredAt.getTime());
}

test("a spread purchase generates one slice per month, summing to exactly what was spent", async () => {
  // Rs 95,000 kiln, spread over 24 months. 9_500_000 / 24 does not divide
  // evenly — 395,833.33 — which is the whole point of testing this amount.
  const purchase = await ledger.createTransaction(businessId, {
    direction: "out",
    occurredAt: DAY("2026-04-10"),
    paidAt: DAY("2026-04-10"),
    sourceId,
    lines: [{ expenseItemId: kilnItemId, qty: "1", unitPriceCents: 95_000_00, spreadMonths: 24 }],
  });

  const slices = await slicesOf(purchase.transaction.id);
  assert.equal(slices.length, 24, "one slice per month");

  const total = slices.reduce((sum, s) => sum + s.amountCents, 0);
  assert.equal(total, 95_000_00, "the slices add back to the purchase, to the cent");

  // The remainder rides on the earliest months, so the schedule never ends on
  // an odd-looking final payment.
  assert.equal(slices[0].amountCents, 3_958_34);
  assert.equal(slices[23].amountCents, 3_958_33);

  // April 2026 through March 2028 — two full years, ending the month before
  // the anniversary, not on it.
  assert.equal(slices[0].header.occurredAt.toISOString().slice(0, 7), "2026-04");
  assert.equal(slices[23].header.occurredAt.toISOString().slice(0, 7), "2028-03");

  // Slices are never paid: the money left once, on the purchase.
  assert.ok(slices.every((s) => s.header.paidAt === null), "no slice claims cash moved");
});

test("accrual charges one month; cash still shows the whole outflow on the day", async () => {
  const april = MONTH("2026-04");
  const accrual = await read.computePnl(businessId, USER, april, "accrual");
  const cash = await read.computePnl(businessId, USER, april, "cash");

  // Accrual: April carries its slice and nothing else. This is the alarm the
  // spread exists to silence — a Rs 95,000 hit that read as a collapse.
  assert.equal(accrual.ladder.periodExpenses, 3_958_34);

  // Cash: the bank really did lose Rs 95,000 in April, and the app never
  // pretends otherwise.
  assert.equal(cash.ladder.periodExpenses, 95_000_00);
});

test("a later month carries its own slice, long after the purchase", async () => {
  const nextJanuary = await read.computePnl(businessId, USER, MONTH("2027-01"), "accrual");
  assert.equal(nextJanuary.ladder.periodExpenses, 3_958_33);

  // And cash sees nothing there, because nothing was paid then.
  const cash = await read.computePnl(businessId, USER, MONTH("2027-01"), "cash");
  assert.equal(cash.ladder.periodExpenses, 0);
});

test("voiding the purchase takes its slices with it", async () => {
  const purchase = await ledger.createTransaction(businessId, {
    direction: "out",
    occurredAt: DAY("2026-06-01"),
    paidAt: DAY("2026-06-01"),
    sourceId,
    lines: [{ expenseItemId: kilnItemId, qty: "1", unitPriceCents: 12_000_00, spreadMonths: 12 }],
  });

  // September is the 6th month of the kiln's 24, and 9,500,000 / 24 leaves a
  // remainder of 8 cents that rides on the first 8 months — so this one is 34.
  const before = await read.computePnl(businessId, USER, MONTH("2026-09"), "accrual");
  assert.equal(before.ladder.periodExpenses, 3_958_34 + 1_000_00, "the kiln slice plus the new one");

  await ledger.voidTransaction(businessId, purchase.transaction.id);

  const slices = await slicesOf(purchase.transaction.id);
  assert.ok(slices.length > 0, "the slices still exist — nothing is hard-deleted");
  assert.ok(slices.every((s) => s.header.status === "void"), "every slice is voided with its purchase");

  const after = await read.computePnl(businessId, USER, MONTH("2026-09"), "accrual");
  assert.equal(after.ladder.periodExpenses, 3_958_34, "September is back to just the kiln");
});

test("slices are not refund history, and not ledger rows either", async () => {
  const purchase = await ledger.createTransaction(businessId, {
    direction: "out",
    occurredAt: DAY("2026-07-03"),
    paidAt: DAY("2026-07-03"),
    sourceId,
    lines: [{ expenseItemId: kilnItemId, qty: "1", unitPriceCents: 6_000_00, spreadMonths: 6 }],
  });

  // The drawer reads `refunds` to print "Refund history". Slices hang off the
  // same parent_transaction_id as a refund does, so without a filter the owner
  // is told a purchase they never refunded was refunded six times.
  const detail = await read.getTransactionDetail(businessId, USER, purchase.transaction.id);
  assert.equal(detail?.refunds.length, 0, "a spread purchase has no refund history");

  // And the ledger list shows the purchase once, not once plus six slices.
  const list = await read.listTransactions(businessId, USER, {
    startDate: "2026-07-01T00:00:00Z",
    endDate: "2026-12-31T23:59:59Z",
    limit: 200,
  } as Parameters<typeof read.listTransactions>[2]);
  const kilnRows = list.items.filter((t) => t.lines.some((l) => l.itemName === "Kiln"));
  assert.equal(kilnRows.length, 1, "one purchase, one row");
  assert.equal(kilnRows[0].lines[0].spreadMonths, 6, "and the row carries the spread so it can explain itself");
});

test("a real refund still blocks the void, so a cascade cannot be used to skip one", async () => {
  const product = await catalog.createRevenueItem(businessId, {
    name: "Ceramic mug",
    type: "product",
    pricingModel: "fixed",
    unitPriceCents: 1_000_00,
  });
  const sale = await ledger.createTransaction(businessId, {
    direction: "in",
    occurredAt: DAY("2026-05-02"),
    paidAt: DAY("2026-05-02"),
    sourceId,
    lines: [{ revenueItemId: product.id, qty: "1" }],
  });
  await ledger.createRefund(businessId, {
    transactionId: sale.transaction.id,
    occurredAt: DAY("2026-05-09"),
    requests: [{ lineId: sale.lines[0].id, qtyRefunded: "1", amountRefundedCents: 1_000_00 }],
  });

  await assert.rejects(
    () => ledger.voidTransaction(businessId, sale.transaction.id),
    (err: unknown) => err instanceof ServiceError && /refund/i.test((err as Error).message),
  );
});

test("what the ledger refuses to spread", async () => {
  const product = await catalog.createRevenueItem(businessId, {
    name: "Workshop seat",
    type: "service",
    pricingModel: "fixed",
    unitPriceCents: 5_000_00,
  });

  // A sale is not a cost.
  await assert.rejects(
    () =>
      ledger.createTransaction(businessId, {
        direction: "in",
        occurredAt: DAY("2026-04-10"),
        sourceId,
        lines: [{ revenueItemId: product.id, qty: "1", spreadMonths: 12 }],
      }),
    (err: unknown) => err instanceof ServiceError,
  );

  // A cost booked against a sale belongs to that sale.
  await assert.rejects(
    () =>
      ledger.createTransaction(businessId, {
        direction: "in",
        occurredAt: DAY("2026-04-10"),
        sourceId,
        lines: [
          { revenueItemId: product.id, qty: "1" },
          { expenseItemId: kilnItemId, qty: "1", unitPriceCents: 500_00, spreadMonths: 12 },
        ],
      }),
    (err: unknown) => err instanceof ServiceError,
  );

  // One month is not a spread, and neither is a fraction of one.
  for (const months of [1, 0, -3, 2.5, 999]) {
    await assert.rejects(
      () =>
        ledger.createTransaction(businessId, {
          direction: "out",
          occurredAt: DAY("2026-04-10"),
          sourceId,
          lines: [{ expenseItemId: kilnItemId, qty: "1", unitPriceCents: 500_00, spreadMonths: months }],
        }),
      (err: unknown) => err instanceof ServiceError,
      `spreadMonths ${months} should be refused`,
    );
  }

  // An order-level discount would be double-counted: taken off the purchase
  // month while the slices were built from the pre-discount figure.
  await assert.rejects(
    () =>
      ledger.createTransaction(businessId, {
        direction: "out",
        occurredAt: DAY("2026-04-10"),
        sourceId,
        orderDiscountCents: 100_00,
        lines: [{ expenseItemId: kilnItemId, qty: "1", unitPriceCents: 500_00, spreadMonths: 12 }],
      }),
    (err: unknown) => err instanceof ServiceError,
  );
});

test("the spread also disappears from the expense breakdown, not just the ladder", async () => {
  // The ladder and the category/type breakdowns read the period through
  // different functions. If only one of them knows the line is capitalised,
  // the page shows a Rs 95,000 equipment row above a Rs 3,958 expense total.
  const april = await read.computePnl(businessId, USER, MONTH("2026-04"), "accrual");
  const total = april.expenseGroups.reduce((sum, row) => sum + row.amountCents, 0);
  assert.equal(total, april.ladder.periodExpenses, "the breakdown adds up to the ladder");

  // Break-even splits the same expenses into fixed and variable and asserts the
  // two halves equal periodExpenses. The kiln is a FIXED item, so a capitalised
  // line the split did not understand would land the whole Rs 95,000 on the
  // fixed side and throw here — which is exactly the alarm we want.
  // line and throw here — which is exactly the alarm we want. Calling it IS
  // the assertion.
  await read.computeBreakEvenReport(businessId, USER, MONTH("2026-04"));
});
