/**
 * Integration tests: spreading a cost over months, against a REAL Postgres.
 *
 * The thing being protected here is that a big one-off purchase stops wrecking
 * the month it was paid in, WITHOUT the money going missing or being counted
 * twice. Three claims, and every one of them has to hold at once:
 *
 *   1. Accrual: the purchase month carries a slice, not the whole purchase.
 *   2. Cash: the full amount still leaves on the day it left. Nothing is hidden.
 *   3. The slices add back to exactly what was spent — no rounding dust.
 *
 * The unit tests in lib/domain prove the schedule arithmetic. These prove the
 * ledger actually wires it up, which is the part that can quietly regress when
 * a read path forgets that a capitalised line spends nothing.
 */
