export function cohortTone(value: number, max: number): string {
  if (max <= 0 || value <= 0) return "bg-muted/40 text-muted-foreground";
  const ratio = value / max;
  // The darkest step is the full green, not 80% of it: mixed with the page it
  // came out light enough that the white label on top scored 3.4, and these
  // cells are 10px.
  if (ratio >= 0.75) return "bg-[color:var(--pl-green)] text-[color:var(--pl-on-fill)]";
  if (ratio >= 0.45) return "bg-[color:color-mix(in_srgb,var(--pl-green)_50%,transparent)] text-[color:var(--pl-ink)]";
  if (ratio >= 0.2) return "bg-[color:color-mix(in_srgb,var(--pl-green)_25%,transparent)] text-[color:var(--pl-ink)]";
  return "bg-[color:var(--pl-green-tint)] text-[color:var(--pl-ink-2)]";
}

export function CohortGrid({
  data,
  state,
}: {
  data: { cohorts: { cohortMonth: string; size: number; cumulativeContributionPerCustomer: number[] }[]; maxOffset: number } | undefined;
  state: FigureState;
}) {
  const cohorts = data?.cohorts ?? [];
  const columns = Math.min(data?.maxOffset ?? 0, 11);
  const max = useMemo(
    () => Math.max(1, ...cohorts.flatMap((c) => c.cumulativeContributionPerCustomer)),
    [cohorts],
  );

  return (
    <section className="pl-glass p-5">
      <h2 className="text-base font-bold text-foreground">Contribution by acquisition cohort</h2>
      <p className="mt-1 text-sm text-muted-foreground">
        Of the customers who first bought in a given month, the average contribution profit each has generated by N months later. Later columns should climb as customers come back.
      </p>
      {cohorts.length === 0 ? (
        <div
          className={`mt-6 rounded-xl border border-dashed border-card-border p-6 text-center text-sm ${state === "settled" || state === "loading" ? "text-muted-foreground" : "text-[color:var(--pl-amber)]"}`}
        >
          {state === "loading"
            ? "Loading…"
            : state === "settled"
              ? "Record sales with customers to unlock cohorts."
              : figureStateSentence(state, "your cohorts")}
        </div>
      ) : (
        <div className="app-scrollbar mt-4 overflow-x-auto">
          <table className="w-full min-w-[640px] text-xs">
            <thead>
              <tr className="text-muted-foreground">
                <th className="py-1.5 pr-3 text-left font-semibold">Cohort</th>
                <th className="px-2 py-1.5 text-right font-semibold">Customers</th>
                {Array.from({ length: columns + 1 }, (_, i) => (
                  <th key={i} className="px-1.5 py-1.5 text-center font-semibold">
                    M{i}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {cohorts.map((c) => (
                <tr key={c.cohortMonth}>
                  <td className="py-1 pr-3 font-medium text-foreground">{c.cohortMonth}</td>
                  <td className="px-2 py-1 text-right tabular-nums text-muted-foreground">{c.size}</td>
                  {Array.from({ length: columns + 1 }, (_, i) => {
                    const value = c.cumulativeContributionPerCustomer[i];
                    return (
                      <td key={i} className="px-0.5 py-0.5">
                        {value === undefined ? (
                          <div className="h-8 rounded-md bg-transparent" />
                        ) : (
                          <div className={`grid h-8 place-items-center rounded-md text-[10px] font-semibold tabular-nums ${cohortTone(value, max)}`}>
                            {formatCents(value).replace("Rs ", "")}
                          </div>
                        )}
                      </td>
                    );
                  })}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </section>
  );
}

/**
 * Which clients are worth having, once their time is counted.
 *
 * The Customers tab already ranks people by contribution from the ledger, which
 * answers "who pays us most" — a different question from "who is worth having",
 * and the gap between the two is the whole point of this module. A client can
 * top the contribution table and still lose money once the hours behind them
 * are priced.
 *
 * Hidden entirely for a business that does not track time. The server refuses
 * those endpoints regardless, so this is about not showing a dead section.
 */
export function ClientsWorthHaving() {
  const { settings } = useStore();
  const period = useInsightsPeriod();
  const enabled = settings.features?.client_profitability ?? false;
  const range = period ? toApiRange(period.range) : { startDate: "", endDate: "" };
  const query = useClientProfitability(range);

  if (!enabled || !period) return null;

  const data = query.data;
  if (!data) return null;

  const clients = data.rows.filter((r) => r.targetType === "client");
  const costed = clients.filter((r) => r.isCosted).sort((a, b) => (a.marginPct ?? 0) - (b.marginPct ?? 0));
  const uncosted = clients.filter((r) => !r.isCosted && r.revenueCents > 0);
  const losing = costed.filter((r) => (r.contributionCents ?? 0) < 0).length;

  return (
    <section className="pl-glass p-5">
      <div className="mb-4 flex flex-wrap items-start justify-between gap-3">
        <div>
          <h2 className="flex items-center gap-2 text-base font-bold text-[color:var(--pl-ink)]">
            <Clock className="h-4 w-4 text-[color:var(--pl-orange-text)]" />
            Which clients are worth having
          </h2>
          <p className="mt-1 text-sm text-[color:var(--pl-ink-2)]">
            The table above ranks who pays you most. This one counts the hours behind them, which is a
            different question — and often a different order.
          </p>
        </div>
        <Link
          href="/insights/worth-having"
          className="inline-flex items-center gap-1 text-sm font-medium text-[color:var(--pl-orange-text)] hover:underline"
        >
          Full breakdown <ArrowRight className="h-3.5 w-3.5" />
        </Link>
      </div>

      {/*
        An empty period says so rather than vanishing. A section that disappears
        looks like a bug to anyone who has just switched the module on, and the
        useful fact — "nothing happened in this window" — is worth one line.
      */}
      {clients.length === 0 ? (
        <p className="rounded-lg border border-card-border bg-muted/20 p-3 text-sm text-muted-foreground">
          No client earned or cost anything in this period. Widen the period above, or{" "}
          <Link href="/record/hours" className="font-medium text-[color:var(--pl-orange-text)] hover:underline">
            log some hours
          </Link>
          .
        </p>
      ) : (
        /* The state first: what the owner is allowed to conclude from this. */
        <p className="mb-4 rounded-lg border border-card-border bg-muted/20 p-3 text-sm text-muted-foreground">
          {DATA_STATE_MESSAGE[data.summary.state]}
          {/*
            Scoped to the CLIENT rows this block actually shows, not the whole
            page. The page-wide flag would caption a table of logged hours with
            a warning about estimates sitting on products it never lists — and
            worse, would read as a contradiction directly under "no hours yet".
          */}
          {clients.some((r) => r.hasEstimates) && (
            <span className="mt-1 block text-xs">
              Some hours here are estimates rather than logged day by day.
            </span>
          )}
        </p>
      )}

      {costed.length > 0 && (
        <div className="app-scrollbar overflow-x-auto">
          <table className="w-full min-w-[560px] text-sm">
            <thead className="bg-muted/30 text-xs uppercase tracking-wide text-muted-foreground">
              <tr>
                <th className="px-4 py-3 text-left font-semibold">Client</th>
                <th className="px-4 py-3 text-right font-semibold">Revenue</th>
                <th className="px-4 py-3 text-right font-semibold">Their time cost</th>
                <th className="px-4 py-3 text-right font-semibold">Left after costs</th>
                <th className="px-4 py-3 text-right font-semibold">Margin</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-card-border/70">
              {/* Worst first: the client quietly losing money is the reason to look. */}
              {costed.slice(0, 8).map((r) => (
                <tr key={`${r.targetType}:${r.targetId}`}>
                  <td className="px-4 py-2.5 font-medium">
                    {r.label}
                    {r.hasEstimates && (
                      <span className="ml-1.5 rounded bg-muted px-1 py-0.5 text-[10px] text-muted-foreground">
                        estimated
                      </span>
                    )}
                  </td>
                  <td className="px-4 py-2.5 text-right tabular-nums">{formatCents(r.revenueCents)}</td>
                  <td className="px-4 py-2.5 text-right tabular-nums text-muted-foreground">
                    {formatCents(r.labourCostCents ?? 0)}
                  </td>
                  <td
                    className={`px-4 py-2.5 text-right tabular-nums font-medium ${
                      (r.contributionCents ?? 0) >= 0 ? "text-[color:var(--pl-green)]" : "text-[color:var(--pl-red)]"
                    }`}
                  >
                    {formatCentsSigned(r.contributionCents ?? 0)}
                  </td>
                  <td className="px-4 py-2.5 text-right tabular-nums text-muted-foreground">
                    {r.marginPct === null ? "—" : `${r.marginPct.toFixed(1)}%`}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {losing > 0 && (
        <p className="mt-3 text-sm text-[color:var(--pl-red)]">
          {losing === 1 ? "One client costs" : `${losing} clients cost`} more in time than they pay. That
          never shows up in a Profit &amp; Loss.
        </p>
      )}

      {/* The honest gap, never a number. */}
      {uncosted.length > 0 && (
        <p className="mt-3 text-sm text-muted-foreground">
          <strong>{formatCents(data.summary.uncostedRevenueCents)}</strong> came from{" "}
          {uncosted.length === 1 ? "a client with" : `${uncosted.length} clients with`} no hours logged, so
          there is no profit figure for {uncosted.length === 1 ? "them" : "them"} — showing one would mean
          inventing it.{" "}
          <Link href="/record/hours" className="font-medium text-[color:var(--pl-orange-text)] hover:underline">
            Log or estimate their time
          </Link>
          .
        </p>
      )}

      {/*
        The same honesty, for costs. Asked of the PERIOD, not of each client:
        a client with no subcontractor genuinely costs nothing beyond hours, so
        blanking their figure would suppress a true zero. What the owner cannot
        tell on their own is whether a zero means "nothing to add" or "nothing
        recorded" — and that is a question about the month, not the client.

        Overheads are named apart deliberately. Folded in, this would report
        most of the month's costs as unassigned forever, and imply rent ought
        to be split across clients, which it never should be.
      */}
      {!data.costAttribution.fullyAttributed && (
        <p className="mt-3 text-sm text-muted-foreground">
          <strong>{formatCents(data.costAttribution.untargetedSplittableCents)}</strong> of this period's
          costs could belong to a client but don't name one, so they are in none of the figures above.{" "}
          <Link
            href="/record/transactions"
            className="font-medium text-[color:var(--pl-orange-text)] hover:underline"
          >
            Say who they were for
          </Link>
          {data.costAttribution.neverSplitCents > 0 && (
            <>
              {" "}
              — separately, {formatCents(data.costAttribution.neverSplitCents)} is rent, wages and the like,
              which is never split by client on purpose
            </>
          )}
          .
        </p>
      )}
    </section>
  );
}
